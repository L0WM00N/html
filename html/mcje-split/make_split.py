#!/usr/bin/env python3
"""
Split a huge single-file game (mcje.html) into small parts, and write a tiny
launcher that is ALSO named mcje.html.

Your site keeps loading ".../html/mcje.html" exactly like before. That file is
now ~6 KB: it downloads the parts from jsDelivr, checks them, joins them in
memory, and starts the game.

Usage:
    python make_split.py mcje-original.html            (writes ./out/)
    python make_split.py mcje-original.html out_dir

Then upload the contents of out_dir/ into your repo's html/ folder:
    html/mcje.html              (the launcher, replaces the 45 MB file)
    html/mcje-parts/part01.bin  (and part02.bin, part03.bin, ...)

Re-run this whenever you replace the original game file.
"""
import hashlib, json, os, sys

# ---- edit these if your repo layout changes ---------------------------------
GITHUB_USER = "L0WM00N"
GITHUB_REPO = "html"
GITHUB_REF = "main"            # branch, or a commit hash to pin (see README note)
REPO_DIR = "html/mcje-parts/"  # where the parts sit inside the repo
PART_BYTES = 8 * 1024 * 1024   # 8 MiB per part (jsDelivr's GitHub limit is ~20 MB)
# -----------------------------------------------------------------------------

LAUNCHER = r"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Minecraft Java Edition</title>
<style>
  html, body { margin: 0; height: 100%; background: #000; color: #ddd; font: 16px/1.5 system-ui, sans-serif; }
  #s { position: fixed; inset: 0; display: flex; flex-direction: column; align-items: center;
       justify-content: center; text-align: center; padding: 16px; white-space: pre-line; gap: 16px; }
  button { font: inherit; padding: 8px 18px; border-radius: 6px; border: 1px solid #666; background: #222; color: #fff; cursor: pointer; }
</style>
</head>
<body>
<div id="s"></div>
<script>
/* Launcher for the split Minecraft file. Generated by make_split.py. */
(() => {
  const USER = "__USER__", REPO = "__REPO__", REF = "__REF__", DIR = "__DIR__";
  const HOSTS = ["cdn", "fastly", "gcore"];                 // jsDelivr mirrors, tried in order
  const BASES = HOSTS.map(h => "https://" + h + ".jsdelivr.net/gh/" + USER + "/" + REPO + "@" + REF + "/" + DIR);
  const PARTS = __PARTS__;                                  // [{file, size, sha256}]
  const TOTAL = __TOTAL__;
  const box = document.getElementById("s");

  const mb = n => (n / 1048576).toFixed(1);
  function show(text, retry) {
    box.textContent = text;
    if (retry) {
      const b = document.createElement("button");
      b.textContent = "Try again";
      b.onclick = () => { box.textContent = ""; run(); };
      box.appendChild(b);
    }
  }

  async function sha256(bytes) {
    if (!(globalThis.crypto && crypto.subtle)) return null;  // skip the check if unavailable
    const d = new Uint8Array(await crypto.subtle.digest("SHA-256", bytes));
    return Array.from(d, x => x.toString(16).padStart(2, "0")).join("");
  }

  // Download one part: tries each mirror, 2 attempts each, with stall timeouts.
  async function getPart(part, onBytes) {
    const errors = [];
    for (const base of BASES) {
      const host = new URL(base).hostname;
      for (let attempt = 1; attempt <= 2; attempt++) {
        const ctl = new AbortController();
        let timer;
        const arm = ms => { clearTimeout(timer); timer = setTimeout(() => ctl.abort(), ms); };
        let got = 0;
        try {
          arm(30000);
          const res = await fetch(base + part.file, { signal: ctl.signal, credentials: "omit" });
          if (!res.ok) { const e = new Error("HTTP " + res.status); e.final = res.status < 500 && res.status !== 429; throw e; }
          const reader = res.body.getReader();
          const chunks = [];
          for (;;) {
            arm(45000);
            const r = await reader.read();
            if (r.done) break;
            chunks.push(r.value); got += r.value.length; onBytes(got);
          }
          const bytes = new Uint8Array(got);
          let at = 0;
          for (const c of chunks) { bytes.set(c, at); at += c.length; }
          if (got !== part.size) throw new Error("size " + got + " instead of " + part.size + " (stale cache?)");
          const h = await sha256(bytes);
          if (h && h !== part.sha256) throw new Error("checksum mismatch (stale cache?)");
          return bytes;
        } catch (e) {
          errors.push(host + " " + part.file + ": " + (e.name === "AbortError" ? "timed out" : e.message));
          if (e.final) break;                                  // 403/404: retrying the same mirror is pointless
          await new Promise(r => setTimeout(r, attempt * 1000));
        } finally {
          clearTimeout(timer);
        }
      }
    }
    throw new Error(errors.join("\n"));
  }

  let running = false;
  async function run() {
    if (running) return;
    running = true;
    try {
      const done = [];
      let finished = 0;
      for (let i = 0; i < PARTS.length; i++) {
        const part = PARTS[i];
        show("Downloading Minecraft… part " + (i + 1) + " of " + PARTS.length);
        const bytes = await getPart(part, got => {
          show("Downloading Minecraft… part " + (i + 1) + " of " + PARTS.length + "\n" + mb(finished + got) + " / " + mb(TOTAL) + " MB");
        });
        finished += bytes.length;
        done.push(bytes);
      }
      show("Starting Minecraft…");
      const html = await new Blob(done).text();
      done.length = 0;                                         // let the pieces be freed
      document.open();
      document.write(html);
      document.close();
    } catch (e) {
      show("Could not download Minecraft.\n\n" + e.message, true);
    } finally {
      running = false;
    }
  }
  run();
})();
</script>
</body>
</html>
"""


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    src = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else "out"
    parts_dir = os.path.join(out, "mcje-parts")
    os.makedirs(parts_dir, exist_ok=True)
    for f in os.listdir(parts_dir):             # clear stale parts from an older split
        if f.startswith("part") and f.endswith(".bin"):
            os.remove(os.path.join(parts_dir, f))

    data = open(src, "rb").read()
    parts = []
    for n, start in enumerate(range(0, len(data), PART_BYTES), 1):
        chunk = data[start:start + PART_BYTES]
        name = "part%02d.bin" % n
        with open(os.path.join(parts_dir, name), "wb") as fh:
            fh.write(chunk)
        parts.append({"file": name, "size": len(chunk), "sha256": hashlib.sha256(chunk).hexdigest()})

    html = (LAUNCHER.replace("__USER__", GITHUB_USER).replace("__REPO__", GITHUB_REPO)
            .replace("__REF__", GITHUB_REF).replace("__DIR__", REPO_DIR)
            .replace("__PARTS__", json.dumps(parts)).replace("__TOTAL__", str(len(data))))
    with open(os.path.join(out, "mcje.html"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(html)
    print("original: %d bytes -> %d parts + launcher (%d bytes)" % (len(data), len(parts), len(html)))
    print("whole-file sha256:", hashlib.sha256(data).hexdigest())


if __name__ == "__main__":
    main()
